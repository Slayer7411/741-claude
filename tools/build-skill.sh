#!/usr/bin/env bash
# Regenerates plugins/741/skills/741/references/ from the 741 source repos,
# bumps the plugin version (YYYY.MM.DD.N) in plugin.json and marketplace.json,
# and runs `claude plugin validate .`.
#
# Source repos are read from DEV_ROOT (default: the parent folder of this repo).
# Each reference = hand-written part(s) in tools/parts/ + copied source docs,
# all passed through the same sanitizer. The run fails if a forbidden name
# is left in the output.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
DEV="${DEV_ROOT:-$(dirname "$REPO")}"
PARTS="$REPO/tools/parts"
SKILL="$REPO/plugins/741/skills/741"
OUT="$SKILL/references"
PJ="$REPO/plugins/741/.claude-plugin/plugin.json"
MJ="$REPO/.claude-plugin/marketplace.json"

for r in MNEMOSYNE-741 MINOS-741 ORPHEUS-741 Charon-741 STYX-741 HELIOS-741; do
  [ -d "$DEV/$r" ] || { echo "missing source repo: $DEV/$r (set DEV_ROOT)" >&2; exit 1; }
done

# Forbidden names. Written with bracket classes so this file does not contain them literally.
FORBIDDEN='t[r]aktor|rek[o]rdbox|nati[v]e instruments|kont[r]ol|ser[a]to|abl[e]ton|mix[x]x|xo[n]e|engine d[j]|virtual ?d[j]|pio[n]eer|den[o]n|numar[k]|dj[m]-|chr[i]stian|slay[e]r7411|/[U]sers/|cs[.]privat|[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}'

# Strip badges, images, html wrappers and dev-process lines; then substitute names.
sanitize() {
  grep -vE 'shields\.io|^!\[|^<p |^</p>|^<img |@|^- agents|^- commits|ENVIRONMENT\.md' |
  sed -E \
    -e 's#/[U]sers/[^ )`"]*#<path>#g' \
    -e 's#~/Library/Pio[n]eer/rek[o]rdbox/master\.db#<xml collection database>#gI' \
    -e 's/rek[o]rdbox-741-export\.xml/<xml export file>/gI' \
    -e 's/T[r]aktor/nml app/gI' \
    -e 's/rek[o]rdbox/xml collection/gI' \
    -e 's/Abl[e]ton Link/link (network tempo sync)/gI' \
    -e 's/Abl[e]ton/daw/gI' \
    -e 's/Kont[r]ol X1 mk2/controller/gI' \
    -e 's/Kont[r]ol/controller/gI' \
    -e 's/Xo[n]e:96/mixer/gI' \
    -e 's/Xo[n]e/mixer/gI' \
    -e 's/Pio[n]eer DJ[M]-[A-Za-z0-9-]+/mixer/gI' \
    -e 's/Pio[n]eer/vendor/gI' \
    -e 's/Nati[v]e Instruments/vendor/gI' \
    -e 's/Ser[a]to/other dj app/gI' \
    -e 's/Mix[x]x/other dj app/gI' \
    -e 's/engine d[j]/other dj app/gI' \
    -e 's/virtual ?d[j]/other dj app/gI' \
    -e 's/Chr[i]stian/owner/g' \
    -e 's/Slay[e]r7411/OWNER/gI' \
    -e 's/\[([^]]*)\]\([^)]*\.md[^)]*\)/\1/g' \
    -e 's/\[([^]]*)\]\(#[^)]*\)/\1/g'
}

# emit <reference name> <item>...   item = P:<file in tools/parts> | S:<path relative to DEV_ROOT>
emit() {
  local name="$1"; shift
  local out="$OUT/$name.md"
  {
    echo "<!-- generated by tools/build-skill.sh. edit tools/parts/ or the source repos, then rebuild. -->"
    for item in "$@"; do
      case "$item" in
        P:*) cat "$PARTS/${item#P:}" ;;
        S:*) echo; cat "$DEV/${item#S:}" ;;
      esac
    done
  } | sanitize > "$out"
  echo "built $out ($(wc -l < "$out" | tr -d ' ') lines)"
}

mkdir -p "$OUT"
emit format   P:format.md
emit writing  P:writing.md
emit minos    P:minos.md S:MINOS-741/docs/FEATURES.md S:MINOS-741/docs/settings.md S:MINOS-741/docs/library.md
emit orpheus  P:orpheus.md S:ORPHEUS-741/docs/SERVICES.md S:ORPHEUS-741/docs/LAN.md
emit charon   P:charon.md S:Charon-741/README.md P:charon-playlist.md
emit styx     P:styx.md S:STYX-741/docs/PLAN.md
emit helios   P:helios.md S:HELIOS-741/docs/PLAN.md

# Leak check on everything that ships in the plugin, and the plugin metadata.
LEAK_RC=0
grep -rniE "$FORBIDDEN" "$REPO/plugins" "$REPO/.claude-plugin" "$REPO/tools" "$REPO/README.md" >&2 || LEAK_RC=$?
if [ "$LEAK_RC" -ne 1 ]; then
  [ "$LEAK_RC" -eq 0 ] && echo "forbidden name or personal detail left in output (see above)" >&2 || echo "leak check failed to run (grep exit $LEAK_RC)" >&2
  exit 1
fi

# Date-based version: YYYY.MM.DD.N, N counts up within a day.
TODAY="$(date +%Y.%m.%d)"
CUR="$(sed -nE 's/.*"version": "([^"]+)".*/\1/p' "$PJ" | head -1)"
if [[ "$CUR" == "$TODAY".* ]]; then
  N=$(( ${CUR##*.} + 1 ))
else
  N=1
fi
NEW="$TODAY.$N"
sed -i '' -E "s/\"version\": \"[^\"]+\"/\"version\": \"$NEW\"/" "$PJ" "$MJ"
echo "version $CUR -> $NEW"

command -v claude >/dev/null || { echo "claude CLI not found" >&2; exit 1; }
(cd "$REPO" && claude plugin validate .)
echo "build OK ($NEW)"
